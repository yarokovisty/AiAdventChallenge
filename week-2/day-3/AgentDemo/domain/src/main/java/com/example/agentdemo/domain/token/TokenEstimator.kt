package com.example.agentdemo.domain.token

import com.example.agentdemo.domain.llm.LlmMessage

/**
 * Порт для **локальной оценки** числа токенов (принцип инверсии зависимостей).
 *
 * Зачем нужна оценка, если сервер и так возвращает точный `usage`:
 * - `usage` приходит только *после* ответа и только для *успешного* запроса;
 * - чтобы показать рост контекста прямо во время набора и **предсказать
 *   переполнение до отправки**, нужно уметь считать токены на клиенте.
 *
 * Это именно оценка: точного токенизатора GLM в Kotlin нет, поэтому реализация
 * опирается на эвристику. Погрешность относительно `usage` мы показываем в UI.
 */
interface TokenEstimator {

    /** Грубая оценка числа токенов в одной строке. */
    fun estimate(text: String): Int

    /**
     * Оценка токенов всего запроса: сумма по сообщениям плюс накладные расходы
     * на разметку ролей (каждое сообщение в chat-формате стоит немного сверх текста).
     */
    fun estimateRequest(messages: List<LlmMessage>): Int
}
