package com.example.agentdemo.domain.llm

/**
 * Порт к языковой модели (принцип инверсии зависимостей).
 *
 * Домен объявляет контракт, а конкретную реализацию (Z.ai через OkHttp)
 * поставляет слой data. Благодаря этому агент не знает ничего о сети и может
 * тестироваться с подменным клиентом.
 */
interface LlmClient {
    /**
     * Отправляет [request] модели и возвращает её ответ вместе с расходом токенов.
     * Бросает исключение при ошибке.
     */
    suspend fun complete(request: LlmRequest): LlmResult
}
