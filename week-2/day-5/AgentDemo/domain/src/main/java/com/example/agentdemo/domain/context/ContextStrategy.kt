package com.example.agentdemo.domain.context

/**
 * Стратегия управления контекстом — то, что переключается в агенте.
 *
 * Каждая стратегия по-своему решает, **что именно** отправлять модели из
 * накопленной истории диалога:
 *
 * - [SLIDING_WINDOW] — только последние N реплик, остальное отбрасывается;
 * - [STICKY_FACTS] — блок важных фактов (ключ→значение) + последние N реплик;
 * - [BRANCHING] — независимые ветки диалога от общего чекпоинта, активная
 *   ветка уходит в модель целиком.
 */
enum class ContextStrategy {
    SLIDING_WINDOW,
    STICKY_FACTS,
    BRANCHING,
}
