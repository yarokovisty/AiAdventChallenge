package com.example.agentdemo.domain.context

/**
 * Параметры управления контекстом диалога.
 *
 * @param keepLastN сколько последних сообщений ленты всегда уходят в модель
 *   «как есть» (хвост, который не сворачивается).
 * @param summarizeEveryM по сколько накопившихся «старых» сообщений за раз
 *   сворачивать в summary. Ре-саммари срабатывает пачкой — чтобы не гонять
 *   модель на каждую реплику.
 *
 * Значения по умолчанию намеренно небольшие: так сжатие легко спровоцировать
 * руками в демо. В задании «каждые 10 сообщений» — лишь пример порога.
 */
data class ContextPolicy(
    val keepLastN: Int = 4,
    val summarizeEveryM: Int = 6,
)
