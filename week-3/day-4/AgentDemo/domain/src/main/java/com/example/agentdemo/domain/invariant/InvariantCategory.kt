package com.example.agentdemo.domain.invariant

/**
 * Категория инварианта — вид жёсткого правила, которое ассистент не вправе
 * нарушить. Категории взяты напрямую из условия задания.
 *
 * Категория носит смысловую нагрузку (группирует инварианты в UI и системном
 * промпте), но на «разрешённость» решения не влияет: нарушать нельзя ни один
 * активный инвариант любой категории.
 *
 * @param title человекочитаемое название (для UI и системного промпта).
 * @param slug латинский ключ — стабилен к переименованию констант enum,
 *   используется как формат хранения в JSON.
 */
enum class InvariantCategory(val title: String, val slug: String) {
    ARCHITECTURE("Архитектура", "architecture"),
    TECH_DECISION("Техническое решение", "tech_decision"),
    STACK("Ограничение по стеку", "stack"),
    BUSINESS_RULE("Бизнес-правило", "business_rule"),
}
