package com.example.agentdemo.domain.task

/**
 * Формализованное состояние задачи — снимок конечного автомата.
 *
 * Хранит ровно то, что просит задание:
 * - [stage] — **этап задачи** (состояние автомата);
 * - [currentStep] — **текущий шаг** внутри этапа;
 * - [expectedAction] — **ожидаемое действие** агента на этом шаге.
 *
 * Плюс то, что делает автомат пригодным к паузе и продолжению без повторных
 * объяснений: [isPaused] — приостановлена ли задача, и [log] — журнал переходов
 * и прогресса. Весь снимок сохраняется на диск и уходит в системный промпт
 * каждого запроса, поэтому после паузы/перезапуска агент продолжает с того же
 * шага — пользователю не нужно заново объяснять контекст.
 *
 * Переходы между состояниями не выполняются здесь — это делает чистый
 * [TaskStateMachine]. Сам [TaskState] остаётся неизменяемым значением.
 *
 * @param goal цель задачи — формулируется один раз при старте.
 * @param stage текущий этап автомата.
 * @param currentStep текущий шаг внутри этапа.
 * @param expectedAction какое действие ожидается от агента сейчас.
 * @param isPaused задача на паузе (выполнение приостановлено на любом этапе).
 * @param log журнал событий автомата (старт, переходы, пауза/продолжение).
 */
data class TaskState(
    val goal: String,
    val stage: TaskStage,
    val currentStep: String,
    val expectedAction: String,
    val isPaused: Boolean = false,
    val log: List<String> = emptyList(),
) {
    /** Задача доведена до конца. */
    val isDone: Boolean get() = stage == TaskStage.DONE
}
