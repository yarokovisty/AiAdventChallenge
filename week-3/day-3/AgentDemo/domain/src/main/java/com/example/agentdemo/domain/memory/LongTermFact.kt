package com.example.agentdemo.domain.memory

/** Вид факта в долговременной памяти. Задаётся пользователем явно при сохранении. */
enum class KnowledgeKind {
    /** Профиль пользователя: имя, предпочтения, контекст о нём. */
    PROFILE,

    /** Принятое решение/договорённость, которое ассистент должен соблюдать. */
    DECISION,

    /** Факт/знание, которое ассистент должен учитывать постоянно. */
    KNOWLEDGE,
}

/**
 * Один элемент долговременной памяти ([MemoryLayer.LONG_TERM]).
 *
 * Переживает и перезапуск приложения, и очистку диалога. В контекст запроса
 * попадает всегда — встраивается в системный промпт сгруппированным по [kind].
 *
 * @param id стабильный идентификатор (для удаления конкретного факта).
 */
data class LongTermFact(
    val id: String,
    val kind: KnowledgeKind,
    val text: String,
)
