package com.example.agentdemo.domain.task

/**
 * Порт хранилища состояния задачи (конечного автомата).
 *
 * Хранит ровно один снимок [TaskState] (или ничего, если активной задачи нет).
 * Отдельное хранилище от памяти и профиля; реализацию (JSON-файл) поставляет
 * слой data. Персистентность — это и есть механизм «паузы»: состояние переживает
 * закрытие приложения, поэтому задачу можно продолжить позже с того же шага.
 */
interface TaskStateRepository {

    /** Загрузить текущее состояние задачи (`null`, если активной задачи нет). */
    suspend fun load(): TaskState?

    /** Перезаписать текущее состояние задачи. */
    suspend fun save(state: TaskState)

    /** Стереть состояние — задача сброшена. */
    suspend fun clear()
}
