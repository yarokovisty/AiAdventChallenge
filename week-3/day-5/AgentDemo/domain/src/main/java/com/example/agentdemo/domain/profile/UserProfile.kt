package com.example.agentdemo.domain.profile

/**
 * Профиль пользователя — слой **персонализации поверх модели памяти**.
 *
 * Описывает не факты (это задача памяти), а *как именно* ассистент должен
 * общаться с конкретным пользователем: его роль/контекст и предпочтения по
 * стилю, формату и ограничениям. Профиль автоматически попадает в системный
 * промпт **каждого** запроса, поэтому пользователю не нужно повторять свои
 * предпочтения в каждом сообщении.
 *
 * Профилей может быть несколько; активен ровно один (см. [UserProfileRepository]).
 * Переключение активного профиля меняет стиль ответов, не трогая память — так
 * видно, что персонализация и память независимы.
 *
 * @param id стабильный идентификатор (для выбора/удаления профиля).
 * @param name человекочитаемый ярлык профиля (напр. «Senior-разработчик»).
 * @param persona кто пользователь: роль и контекст о нём.
 * @param style предпочитаемый стиль и тон ответа.
 * @param format предпочитаемый формат ответа (структура, длина, оформление).
 * @param constraints ограничения — чего делать не нужно / жёсткие требования.
 */
data class UserProfile(
    val id: String,
    val name: String,
    val persona: String = "",
    val style: String = "",
    val format: String = "",
    val constraints: String = "",
) {
    /** Есть ли что встраивать в системный промпт (хоть одно предпочтение задано). */
    val hasPreferences: Boolean
        get() = persona.isNotBlank() || style.isNotBlank() ||
            format.isNotBlank() || constraints.isNotBlank()
}
