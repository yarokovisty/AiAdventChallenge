package com.example.agentdemo.domain.invariant

/**
 * Инвариант — **жёсткое правило, которое ассистент не имеет права нарушить**.
 *
 * В отличие от профиля (он задаёт, *как* отвечать) и памяти (она задаёт, *что*
 * ассистент знает), инвариант задаёт, *что запрещено предлагать*. Инварианты
 * хранятся отдельным слоем (свой файл, см. [InvariantRepository]) и автоматически
 * попадают в системный промпт **каждого** запроса — самым приоритетным блоком.
 *
 * Ассистент обязан сверять любое предлагаемое решение с каждым активным
 * инвариантом и отказываться от решений, которые его нарушают, называя
 * конкретный инвариант и объясняя причину отказа.
 *
 * @param id стабильный идентификатор (для редактирования/удаления).
 * @param category вид правила: архитектура / техрешение / стек / бизнес-правило.
 * @param rule сама формулировка запрета или требования.
 * @param rationale почему это правило принято (помогает ассистенту объяснять отказ).
 * @param isActive учитывается ли инвариант сейчас. Неактивный остаётся в хранилище,
 *   но в запрос не уходит — так правило можно временно снять, не удаляя.
 */
data class Invariant(
    val id: String,
    val category: InvariantCategory,
    val rule: String,
    val rationale: String = "",
    val isActive: Boolean = true,
)
