package com.example.agentdemo.domain.memory

/**
 * Рабочая память ([MemoryLayer.WORKING]) — данные текущей задачи.
 *
 * Живёт, пока пользователь работает над задачей: задаётся явно, влияет на ответы
 * как «контекст текущей задачи» в системном промпте и стирается по команде
 * «Завершить задачу». В отличие от долговременной памяти не должна переживать
 * завершение задачи.
 *
 * @param task короткая формулировка текущей задачи.
 * @param notes заметки/факты, собранные по ходу работы над задачей.
 */
data class WorkingMemory(
    val task: String,
    val notes: List<String> = emptyList(),
)
