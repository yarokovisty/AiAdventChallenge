package com.example.agentdemo.domain.memory

/**
 * Три явных слоя памяти ассистента.
 *
 * Слои различаются сроком жизни и тем, как они попадают в контекст запроса к LLM:
 * - [SHORT_TERM] — текущий диалог (реплики), живёт как список сообщений и уходит
 *   в запрос как история; стирается при очистке диалога;
 * - [WORKING] — данные текущей задачи (задача + заметки по ней), вставляются в
 *   системный промпт на время работы над задачей и стираются по её завершении;
 * - [LONG_TERM] — профиль, решения и знания; всегда вставляются в системный
 *   промпт и переживают и перезапуск, и очистку диалога.
 *
 * Каждый слой хранится отдельно (своё хранилище), а наполняется явно — см.
 * соответствующие порты и интенты экрана чата.
 */
enum class MemoryLayer { SHORT_TERM, WORKING, LONG_TERM }
